io.on('connection', (socket) => {
  socket.emit('leaderboard', leaderboardSnapshot());
  socket.emit('game-window-all', allGameWindowsSnapshot());
  socket.emit('tournament:round-state-all', allRoundStates());
  socket.emit('tournament:top-score-all', allTournamentSnapshots());

  socket.on('admin:login', ({ password }, callback) => {
    const ok = typeof password === 'string' && password === ADMIN_PASSWORD;
    if (ok) {
      socket.isAdmin = true;
      adminSocketIds.add(socket.id);
    }
    if (typeof callback === 'function') {
      callback({
        ok,
        state: ok ? allGameWindowsSnapshot() : undefined,
        playerCount: ok ? players.size : undefined,
        flags: ok ? cheatFlags.slice(-50).reverse() : undefined,
        // Bundled directly into the response (rather than relying on the
        // connection-time broadcasts) since a listener for those only gets
        // attached AFTER login succeeds -- by then the one-shot connection
        // broadcast has already fired and would otherwise be missed,
        // leaving e.g. the Live Top Score page showing nothing until the
        // next live score change.
        roundStates: ok ? allRoundStates() : undefined,
        topScores: ok ? allTournamentSnapshots() : undefined,
      });
    }
  });

  socket.on('admin:open', ({ game }, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    if (!GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid game' });
      return;
    }
    openGameWindow(game);
    if (typeof callback === 'function') callback({ ok: true, state: gameWindowSnapshot(game) });
  });

  socket.on('admin:close', ({ game }, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    if (!GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid game' });
      return;
    }
    closeGameWindowNow(game);
    if (typeof callback === 'function') callback({ ok: true, state: gameWindowSnapshot(game) });
  });

  socket.on('admin:set-hidden', ({ game, hidden }, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    if (!GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid game' });
      return;
    }
    gameHidden[game] = Boolean(hidden);
    broadcastGameWindow(game);
    if (typeof callback === 'function') callback({ ok: true, state: gameWindowSnapshot(game) });
  });

  socket.on('admin:set-tournament-hidden', ({ game, hidden }, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    if (!GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid game' });
      return;
    }
    tournamentHidden[game] = Boolean(hidden);
    broadcastGameWindow(game);
    if (typeof callback === 'function') callback({ ok: true, state: gameWindowSnapshot(game) });
  });

  socket.on('register', ({ playerId, name }) => {
    if (typeof playerId !== 'string' || !playerId) return;
    const player = getOrCreatePlayer(playerId);
    player.name = sanitizeName(name);
    io.emit('leaderboard', leaderboardSnapshot());
  });

  socket.on('score:submit', ({ playerId, name, game, score, detail, mode }) => {
    if (typeof playerId !== 'string' || !playerId) return;
    if (!GAMES.includes(game)) return;

    const player = getOrCreatePlayer(playerId);
    if (name) player.name = sanitizeName(name);
    const incoming = clampScore(score, maxScoreFor(game, mode));
    // Only replace the stored detail (time/moves/etc.) when this run matches
    // or beats the recorded best, so it always describes THAT score, not
    // whatever run happened to submit most recently.
    if (incoming >= (player.scores[game] || 0)) {
      player.details[game] = sanitizeDetail(detail);
    }
    player.scores[game] = Math.max(player.scores[game] || 0, incoming);
    const now = Date.now();
    player.updatedAt = now;
    player.gameUpdatedAt[game] = now;

    io.emit('leaderboard', leaderboardSnapshot());
  });

  // Reserves one of the player's lifetime attempts for a game before they're
  // allowed to see the board. Consumed on request, not on completion, so a
  // disqualified (tab-switch) run still costs an attempt like a normal one.
  socket.on('game:start-attempt', ({ playerId, name, game }, callback) => {
    if (typeof playerId !== 'string' || !playerId || !GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid request' });
      return;
    }
    const player = getOrCreatePlayer(playerId);
    if (name) player.name = sanitizeName(name);
    const max = MAX_ATTEMPTS[game] || null;
    const used = player.attempts[game] || 0;
    if (max && used >= max) {
      if (typeof callback === 'function') callback({ ok: false, error: 'max-attempts', attemptsUsed: used, attemptsMax: max });
      return;
    }
    player.attempts[game] = used + 1;
    if (typeof callback === 'function') callback({ ok: true, attemptsUsed: player.attempts[game], attemptsMax: max });
  });

  // Reserves one of a player's TOURNAMENT_MAX_ATTEMPTS retries within the
  // CURRENT tournament round (Sudoku/Memory only -- see TOURNAMENT_RETRY_GAMES).
  // Separate from game:start-attempt's lifetime Solo+Tournament cap above:
  // this only gates retries inside an already-active Tournament round, and
  // resets on admin:new-tournament-round, not per-player ever.
  socket.on('tournament:request-attempt', ({ playerId, game }, callback) => {
    if (typeof playerId !== 'string' || !playerId || !TOURNAMENT_RETRY_GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid-game' });
      return;
    }
    if (tournamentRound[game].phase !== 'active') {
      if (typeof callback === 'function') callback({ ok: false, error: 'not-active' });
      return;
    }
    const used = tournamentAttempts[game].get(playerId) || 0;
    if (used >= TOURNAMENT_MAX_ATTEMPTS) {
      if (typeof callback === 'function') {
        callback({ ok: false, error: 'exhausted', attemptsUsed: used, attemptsMax: TOURNAMENT_MAX_ATTEMPTS });
      }
      return;
    }
    tournamentAttempts[game].set(playerId, used + 1);
    if (typeof callback === 'function') {
      callback({ ok: true, attemptsUsed: used + 1, attemptsMax: TOURNAMENT_MAX_ATTEMPTS });
    }
  });

  // Anti-cheat signal from a game page (tab-switch disqualification, brute-force
  // guess pattern, implausible solve speed, ...). Never blocks play server-side —
  // it's surfaced to the admin panel for a human to judge.
  socket.on('cheat:flag', ({ playerId, name, game, reason, detail }) => {
    if (typeof playerId !== 'string' || !playerId) return;
    recordCheatFlag({ playerId, name, game, reason, detail });
  });

  // Clears everyone's used-attempt count for one game (or all games), without
  // touching scores — for undoing lockouts during testing or between rounds.
  socket.on('admin:reset-attempts', ({ game }, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    if (game && !GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid game' });
      return;
    }
    const gamesToReset = game ? [game] : GAMES;
    let playerCount = 0;
    players.forEach((player) => {
      gamesToReset.forEach((g) => { player.attempts[g] = 0; });
      playerCount += 1;
    });
    if (typeof callback === 'function') callback({ ok: true, playerCount, games: gamesToReset });
  });

  // Hands out the current shared shuffle/draw for a tournament-capable game
  // and places the player in its Tournament lobby, generating fresh content
  // on first request if this is the very first player to ask. Only reachable
  // while the round is still in the 'lobby' phase -- once the admin has
  // started it (admin:tournament-start), late joiners are turned away and
  // have to wait for the admin to start a new round (admin:new-tournament-round
  // resets back to 'lobby'). Anyone can call this (no admin gate) --
  // Tournament mode is still only reachable from a page already behind that
  // game's normal join-window gate, same as Solo mode.
  socket.on('tournament:join', ({ playerId, name, game }, callback) => {
    if (!TOURNAMENT_GAMES.includes(game)) { if (typeof callback === 'function') callback({ ok: false, error: 'invalid-game' }); return; }
    if (tournamentRound[game].phase !== 'lobby') {
      if (typeof callback === 'function') callback({ ok: false, error: 'round-in-progress' });
      return;
    }
    const content = getOrCreateTournamentContent(game);
    if (typeof playerId === 'string' && playerId) {
      tournamentParticipants[game].set(playerId, sanitizeName(name));
      // A fresh attempt starts out with no live score of its own -- otherwise
      // this player would keep "leading" on their last attempt's final tally
      // until they answer their first question in the new one.
      tournamentLiveScores[game].delete(playerId);
      broadcastTournamentTop(game); // playerCount (and maybe the standings) just changed
      broadcastRoundState(game); // playerCount just changed too
    }
    if (typeof callback === 'function') {
      callback({ ok: true, content, standings: tournamentSnapshot(game), round: roundStatePayload(game) });
    }
  });

  // A tournament player reports that they've finished (correctly answered,
  // timed out, or otherwise resolved) the CURRENT question/word -- not just
  // to update their live score (like the old tournament:progress this
  // replaces), but so the server can tell once EVERY joined participant has
  // finished this question and end the turn early for anyone still waiting
  // out their own clock (see tournament:question-over below). A stale report
  // -- the round having since moved on, or the wrong questionIndex -- is
  // ignored, since it can't mean anything for the CURRENT question.
  // `final` marks this report as a CONFIRMED completed attempt (Scramble/
  // Proverb: every report, since each is a question actually resolving;
  // Sudoku/Memory: only finish/give-up/timeout, not the periodic in-progress
  // ticks from updateLiveScore()) -- see liveStandings() above for why that
  // distinction matters.
  socket.on('tournament:question-done', ({ playerId, name, game, questionIndex, score, final }) => {
    if (typeof playerId !== 'string' || !playerId) return;
    if (!TOURNAMENT_GAMES.includes(game)) return;
    const round = tournamentRound[game];
    if (round.phase !== 'active' || questionIndex !== round.questionIndex) return;
    const incoming = clampScore(score, maxScoreFor(game, 'tournament'));
    const existing = tournamentLiveScores[game].get(playerId) || { bestFinalScore: 0, liveScore: 0 };
    tournamentLiveScores[game].set(playerId, {
      name: sanitizeName(name),
      bestFinalScore: final ? Math.max(existing.bestFinalScore, incoming) : existing.bestFinalScore,
      // Reset the transient once an attempt concludes -- a fresh retry's own
      // ticks will repopulate it, so it never carries over a now-irrelevant
      // in-progress value from the attempt that just ended.
      liveScore: final ? 0 : incoming,
      updatedAt: Date.now(),
    });
    broadcastTournamentTop(game);
    if (final) {
      tournamentQuestionDone[game].add(playerId);
      if (tournamentQuestionDone[game].size >= tournamentParticipants[game].size) {
        io.emit('tournament:question-over', { game, questionIndex });
      }
    }
  });

  // Regenerates a fresh shared shuffle/draw for a tournament-capable game and
  // resets its round back to a fresh 'lobby' -- e.g. to start a brand new
  // round once the current one has finished (or to abort one in progress).
  // Players already mid-question keep playing with their old content to a
  // natural finish (their local `words`/`rounds` array was already fetched at
  // join time), but the shared pacing (admin:tournament-start/-next) is reset,
  // so anyone still waiting on a "next question" from the old round is now
  // stuck -- only expected to be used between rounds, not mid-round.
  socket.on('admin:new-tournament-round', ({ game }, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    if (!TOURNAMENT_GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid-game' });
      return;
    }
    tournamentContent[game] = generateTournamentContent(game);
    tournamentLiveScores[game] = new Map();
    tournamentParticipants[game] = new Map();
    tournamentQuestionDone[game] = new Set();
    tournamentRound[game] = freshTournamentRound(game);
    if (TOURNAMENT_RETRY_GAMES.includes(game)) tournamentAttempts[game] = new Map();
    broadcastTournamentTop(game);
    broadcastRoundState(game);
    if (typeof callback === 'function') callback({ ok: true });
  });

  // Releases everyone currently in a Tournament's lobby to start question 0
  // together. Only valid from the 'lobby' phase (see tournament:join, which
  // stops accepting new joins once this fires).
  socket.on('admin:tournament-start', ({ game }, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    if (!TOURNAMENT_GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid-game' });
      return;
    }
    if (tournamentRound[game].phase !== 'lobby') {
      if (typeof callback === 'function') callback({ ok: false, error: 'already-started' });
      return;
    }
    tournamentRound[game].phase = 'active';
    tournamentRound[game].questionIndex = 0;
    tournamentQuestionDone[game] = new Set();
    broadcastRoundState(game);
    if (typeof callback === 'function') callback({ ok: true });
  });

  // Releases everyone currently waiting (their own question having already
  // ended) into the next question. Not valid once the last question has
  // already begun -- there's nothing further to advance to; each player's own
  // client finishes their run locally when their final question ends.
  socket.on('admin:tournament-next', ({ game }, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    if (!TOURNAMENT_GAMES.includes(game)) {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid-game' });
      return;
    }
    const round = tournamentRound[game];
    if (round.phase !== 'active') {
      if (typeof callback === 'function') callback({ ok: false, error: 'not-active' });
      return;
    }
    if (round.questionIndex + 1 >= round.totalQuestions) {
      if (typeof callback === 'function') callback({ ok: false, error: 'already-last-question' });
      return;
    }
    round.questionIndex += 1;
    tournamentQuestionDone[game] = new Set();
    broadcastRoundState(game);
    if (typeof callback === 'function') callback({ ok: true });
  });

  // Populates (or clears) the fake players above for previewing the leaderboard
  // UI. Admin-only, and never runs on its own — see SEED_DEMO_DATA below for
  // the opt-in startup version.
  socket.on('admin:seed-demo-data', (payload, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    const count = seedDemoData();
    io.emit('leaderboard', leaderboardSnapshot());
    if (typeof callback === 'function') callback({ ok: true, count });
  });

  socket.on('admin:clear-demo-data', (payload, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    const removed = clearDemoData();
    io.emit('leaderboard', leaderboardSnapshot());
    if (typeof callback === 'function') callback({ ok: true, removed });
  });

  socket.on('admin:clear-bot-data', (payload, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    const removed = clearBotData();
    io.emit('leaderboard', leaderboardSnapshot());
    if (typeof callback === 'function') callback({ ok: true, removed });
  });

  // Snapshots the current top 10 for ONE board ('overall' or a game key) in
  // rank order and broadcasts it so the big-screen leaderboard can run that
  // board's reveal ceremony. The client freezes on this snapshot for the
  // animation — it does not reflect scores that come in mid-ceremony. Each
  // of the 5 boards is revealed independently, on its own admin button.
  socket.on('admin:reveal-results', ({ board }, callback) => {
    if (!socket.isAdmin) {
      if (typeof callback === 'function') callback({ ok: false, error: 'not authorized' });
      return;
    }
    let top10;
    if (board === 'overall') {
      top10 = leaderboardSnapshot().filter((p) => p.total > 0).slice(0, 10);
    } else if (GAMES.includes(board)) {
      top10 = topForGame(board, 10);
    } else {
      if (typeof callback === 'function') callback({ ok: false, error: 'invalid board' });
      return;
    }
    io.emit('reveal-results', { board, top10 });
    if (typeof callback === 'function') callback({ ok: true, count: top10.length });
  });

  socket.on('disconnect', () => {
    adminSocketIds.delete(socket.id);
  });
});

