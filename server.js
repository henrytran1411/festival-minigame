// -- Tournament mode (all 4 games) ------------------------------------------
// Every scored game's Tournament mode shares the same lobby/pacing shell:
// players tournament:join a 'lobby' (see tournamentRound/tournamentParticipants
// below), the admin releases everyone together (admin:tournament-start), and
// each player's live in-progress score feeds tournamentLiveScores so the
// admin's Live Top Score page can show it. TOURNAMENT_GAMES (all 4) controls
// that shell; TOURNAMENT_CONTENT_SHARED_GAMES (Proverb/Scramble only)
// controls a second, separate thing -- actual shared puzzle CONTENT.
//
// For Proverb/Scramble, Tournament also hands everyone the exact same
// shuffled draw (see generateTournamentContent) and paces them through it
// question-by-question (questionIndex, admin:tournament-next) -- solo mode's
// own random draw isn't really comparable across players otherwise. Memory
// Match and Sudoku are deliberately left OUT of content-sharing: each player
// still gets their own random board/puzzle (same as Solo), so one player
// solving it can't hand the layout/answers to others in the same round.
// Picking Tournament there only gets you the shared lobby/live-score shell,
// plus tagging the attempt for the leaderboard -- totalQuestions is just 1
// (see freshTournamentRound), a single continuous attempt with no staged
// "next question" to advance through.
const TOURNAMENT_GAMES = GAMES;
const TOURNAMENT_CONTENT_SHARED_GAMES = ['proverb', 'scramble'];
const TOURNAMENT_PROVERB_POOL_SIZE = 40; // must match proverb.js's PROVERB_POOL.length
const TOURNAMENT_PROVERB_ROUNDS = 15; // must match proverb.js's ROUNDS_PER_GAME
const TOURNAMENT_SCRAMBLE_POOL_SIZE = 20; // must match scramble.js's WORD_POOL.length
const TOURNAMENT_SCRAMBLE_ROUND_LENGTH = 15; // Tournament-only round length (Solo stays scramble.js's WORDS_PER_GAME = 12)
// Fixed-position words for Tournament mode -- 1-based question number -> index
// into scramble.js's WORD_POOL. Must stay in sync with that array's order:
// index 12 is 'SMARTDEV', index 13 is 'CÔNG ĐOÀN'. Every Tournament round
// gets these two words at exactly these positions; the remaining positions
// are randomly drawn (without repeats) from the rest of the pool.
const TOURNAMENT_SCRAMBLE_FIXED_POSITIONS = { 10: 12, 15: 13 };

function shuffleArray(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// One shared content set per tournament-capable game -- regenerated by the
// admin (a "New Tournament Round" action) or generated lazily the first
// time anyone asks for it. Players already mid-game keep whatever content
// they already fetched; only players who join AFTER a regeneration get the
// new one, which is fine since this isn't a live synchronized round.
function generateTournamentContent(game) {
  if (game === 'proverb') {
    const indices = Array.from({ length: TOURNAMENT_PROVERB_POOL_SIZE }, (_, i) => i);
    return { proverbOrder: shuffleArray(indices).slice(0, TOURNAMENT_PROVERB_ROUNDS) };
  }
  if (game === 'scramble') {
    const fixedPositions = TOURNAMENT_SCRAMBLE_FIXED_POSITIONS; // { 10: 12, 15: 13 }
    const fixedIndices = new Set(Object.values(fixedPositions));
    const remainingPoolIndices = Array.from({ length: TOURNAMENT_SCRAMBLE_POOL_SIZE }, (_, i) => i)
      .filter((i) => !fixedIndices.has(i));
    const randomSlotCount = TOURNAMENT_SCRAMBLE_ROUND_LENGTH - fixedIndices.size;
    const randomDraw = shuffleArray(remainingPoolIndices).slice(0, randomSlotCount);

    const wordOrder = new Array(TOURNAMENT_SCRAMBLE_ROUND_LENGTH).fill(null);
    Object.entries(fixedPositions).forEach(([position, poolIndex]) => {
      wordOrder[Number(position) - 1] = poolIndex;
    });
    let randomCursor = 0;
    for (let i = 0; i < wordOrder.length; i += 1) {
      if (wordOrder[i] === null) wordOrder[i] = randomDraw[randomCursor++];
    }
    return { wordOrder };
  }
  return null;
}

const tournamentContent = {}; // game -> content, only for TOURNAMENT_GAMES
function getOrCreateTournamentContent(game) {
  if (!tournamentContent[game]) tournamentContent[game] = generateTournamentContent(game);
  return tournamentContent[game];
}

// game -> Map<playerId, { name, score, updatedAt }> -- each player's LIVE,
// in-progress score for their current Tournament attempt at that game.
// Distinct from players.scores[game] (only updated once a run fully
// finishes, see score:submit): this updates after every single question/word
// a player answers, so everyone currently in that Tournament can watch the
// lead change in real time. Reset per-player on a fresh tournament:join
// (so a new attempt doesn't start out "leading" on a stale old score), and
// entirely whenever the admin starts a new tournament round.
const tournamentLiveScores = {};
TOURNAMENT_GAMES.forEach((g) => { tournamentLiveScores[g] = new Map(); });

// game -> Map<playerId, name> -- every distinct player who has joined the
// CURRENT tournament round for that game (added on tournament:join, kept
// even after they finish so the "X joined" count stays accurate for the
// whole round). Reset only when the admin starts a new tournament round.
const tournamentParticipants = {};
TOURNAMENT_GAMES.forEach((g) => { tournamentParticipants[g] = new Map(); });

// Sudoku and Memory Match generate a fresh random puzzle/board per attempt
// (unlike Scramble/Proverb's identical shared content for everyone), so a
// retry there is fair and meaningful -- each joined participant gets up to
// TOURNAMENT_MAX_ATTEMPTS plays within the current round (see
// tournament:request-attempt below), independent of Sudoku's separate
// lifetime Solo+Tournament cap (MAX_ATTEMPTS). Reset whenever the admin
// starts a new tournament round.
